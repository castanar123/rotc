    <script>
        let selectedRifles = [];

        document.addEventListener('DOMContentLoaded', function() {
            // Initialize rifle selection
            const rifleCheckboxes = document.querySelectorAll('.rifle-select');
            const selectedCountElement = document.getElementById('selected-count');
            const submitButton = document.getElementById('submit-borrowing');

            rifleCheckboxes.forEach(checkbox => {
                checkbox.addEventListener('change', function() {
                    const rifleId = parseInt(this.value);
                    const rifleCard = this.closest('.rifle-card');

                    if (this.checked) {
                        selectedRifles.push(rifleId);
                        rifleCard.classList.add('selected');
                    } else {
                        selectedRifles = selectedRifles.filter(id => id !== rifleId);
                        rifleCard.classList.remove('selected');
                    }

                    selectedCountElement.textContent = selectedRifles.length;
                    submitButton.disabled = selectedRifles.length === 0;
                });
            });

            // Handle form submission
            submitButton.addEventListener('click', function() {
                const borrowerName = document.getElementById('borrower_name').value.trim();
                const notes = document.getElementById('notes').value.trim();
                const qrCodeId = document.getElementById('qr_code_id').value;

                if (!borrowerName) {
                    alert('Please enter the borrower name.');
                    return;
                }

                if (selectedRifles.length === 0) {
                    alert('Please select at least one rifle to borrow.');
                    return;
                }

                // Disable button to prevent double submission
                this.disabled = true;
                this.innerHTML = '<i class="fas fa-spinner fa-spin"></i> Processing...';

                // Submit the borrowing request
                fetch('process_borrowing.php', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                    },
                    body: JSON.stringify({
                        qr_code_id: qrCodeId,
                        borrower_name: borrowerName,
                        rifle_ids: selectedRifles,
                        notes: notes
                    })
                })
                .then(response => response.json())
                .then(data => {
                    if (data.success) {
                        alert('Rifles borrowed successfully!');
                        window.location.href = 'rifle_management.php?view=borrowings';
                    } else {
                        alert('Error: ' + data.message);
                        this.disabled = false;
                        this.innerHTML = '<i class="fas fa-check"></i> Submit Borrowing';
                    }
                })
                .catch(error => {
                    console.error('Error:', error);
                    alert('An error occurred while processing the borrowing.');
                    this.disabled = false;
                    this.innerHTML = '<i class="fas fa-check"></i> Submit Borrowing';
                });
            });
        });
    </script>

