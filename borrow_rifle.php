$sql = "SELECT r.id, r.rifle_number, r.model, r.notes AS condition_notes 
        FROM rifles r 
        LEFT JOIN rifle_borrowings rb ON JSON_CONTAINS(rb.rifle_ids, CAST(r.id AS JSON)) AND rb.status = 'active'
        WHERE r.status = 'available' AND rb.id IS NULL
        ORDER BY r.rifle_number";
$rifles_result = $link->query($sql);

