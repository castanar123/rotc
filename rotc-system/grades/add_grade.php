        // Grade scale change handler
        document.getElementById('grade_scale').addEventListener('change', function() {
            const gradeInput = document.getElementById('grade');
            const scale = this.value;
            
            switch(scale) {
                case 'percentage':
                    gradeInput.placeholder = 'Enter percentage (0-100)';
                    gradeInput.type = 'number';
                    gradeInput.min = '0';
                    gradeInput.max = '100';
                    break;
                case 'letter':
                    gradeInput.placeholder = 'Enter letter grade (A, B, C, D, F)';
                    gradeInput.type = 'text';
                    gradeInput.removeAttribute('min');
                    gradeInput.removeAttribute('max');
                    break;
                case 'points':
                    gradeInput.placeholder = 'Enter points earned';
                    gradeInput.type = 'number';
                    gradeInput.min = '0';
                    gradeInput.removeAttribute('max');
                    break;
                case 'pass_fail':
                    gradeInput.placeholder = 'Enter Pass or Fail';
                    gradeInput.type = 'text';
                    gradeInput.removeAttribute('min');
                    gradeInput.removeAttribute('max');
                    break;
            }
        });

        // Form validation
        document.getElementById('gradeForm').addEventListener('submit', function(e) {
            const grade = document.getElementById('grade').value.trim();
            const scale = document.getElementById('grade_scale').value;
            
            // Validate grade based on scale
            if (scale === 'percentage') {
                const numGrade = parseFloat(grade);
                if (isNaN(numGrade) || numGrade < 0 || numGrade > 100) {
                    e.preventDefault();
                    alert('Please enter a valid percentage between 0 and 100.');
                    return;
                }
            } else if (scale === 'letter') {
                const validGrades = ['A', 'B', 'C', 'D', 'F', 'A+', 'A-', 'B+', 'B-', 'C+', 'C-', 'D+', 'D-'];
                if (!validGrades.includes(grade.toUpperCase())) {
                    e.preventDefault();
                    alert('Please enter a valid letter grade (A, B, C, D, F with optional + or -).');
                    return;
                }
            } else if (scale === 'pass_fail') {
                const validValues = ['PASS', 'FAIL', 'P', 'F'];
                if (!validValues.includes(grade.toUpperCase())) {
                    e.preventDefault();
                    alert('Please enter Pass/Fail or P/F.');
                    return;
                }
            }
        });

        // Preview function
        function previewGrade() {
            const cadetSelect = document.getElementById('cadet_id');
            const cadetName = cadetSelect.options[cadetSelect.selectedIndex].text;
            const eventName = document.getElementById('event_name').value;
            const grade = document.getElementById('grade').value;
            const scale = document.getElementById('grade_scale').value;
            const comments = document.getElementById('comments').value;
            
            if (!cadetSelect.value || !eventName || !grade) {
                alert('Please fill in the required fields to preview.');
                return;
            }
            
            const preview = `
                Cadet: ${cadetName}
                Event: ${eventName}
                Grade: ${grade} (${scale})
                Comments: ${comments || 'None'}
            `;
            
            alert(preview);
        }

