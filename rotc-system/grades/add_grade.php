                grade: document.getElementById('grade').value,
                comments: document.getElementById('comments').value
            };
            
            if (formData.cadet_id || formData.event_name || formData.grade) {
                localStorage.setItem('grade_draft', JSON.stringify(formData));
            }
        }, 30000);

        // Load draft on page load
        window.addEventListener('load', function() {
            const draft = localStorage.getItem('grade_draft');
            if (draft) {
                const draftData = JSON.parse(draft);
                if (confirm('A draft was found. Would you like to restore it?')) {
                    document.getElementById('cadet_id').value = draftData.cadet_id;
                    document.getElementById('event_name').value = draftData.event_name;
