// Fetch cadets in the same platoon
$cadets = [];
$sql = "SELECT cp.*, u.username, u.email FROM cadet_profiles cp 
        JOIN users u ON cp.user_id = u.id 
        WHERE cp.platoon = ? ORDER BY cp.last_name, cp.first_name";
if ($stmt = $link->prepare($sql)) {
    $stmt->bind_param("s", $officer_platoon);
    $stmt->execute();
    $result = $stmt->get_result();
    while ($row = $result->fetch_assoc()) {
        $cadets[] = $row;
    }
    $stmt->close();
}

// Get platoon statistics
$total_cadets = count($cadets);
