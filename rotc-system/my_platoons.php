// Count active cadets (those with recent activity)
$sql = "SELECT COUNT(DISTINCT cp.id) as active_count FROM cadet_profiles cp 
        JOIN users u ON cp.user_id = u.id 
        WHERE cp.platoon = ? AND u.created_at >= DATE_SUB(NOW(), INTERVAL 30 DAY)";
if ($stmt = $link->prepare($sql)) {
    $stmt->bind_param("s", $officer_platoon);
    $stmt->execute();
    $result = $stmt->get_result();
    if ($row = $result->fetch_assoc()) {
        $active_cadets = $row['active_count'];
