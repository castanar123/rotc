        function exportLogs() {
            const logs = [];
            document.querySelectorAll('.data-table tbody tr').forEach(row => {
                const cells = row.querySelectorAll('td');
                const logData = Array.from(cells).map(cell => cell.textContent.trim()).join('\t');
                logs.push(logData);
            });

            const headers = Array.from(document.querySelectorAll('.data-table thead th')).map(th => th.textContent.trim()).join('\t');
            const csvContent = headers + '\n' + logs.join('\n');

            const blob = new Blob([csvContent], { type: 'text/csv' });
            const url = URL.createObjectURL(blob);
            const a = document.createElement('a');
            a.href = url;
            a.download = 'attendance-logs.csv';
            document.body.appendChild(a);
            a.click();
            document.body.removeChild(a);
            URL.revokeObjectURL(url);
        }

        // Search functionality
        document.getElementById('searchInput').addEventListener('input', function() {
            const searchTerm = this.value.toLowerCase();
            const rows = document.querySelectorAll('.data-table tbody tr');
            
            rows.forEach(row => {
                const text = row.textContent.toLowerCase();
                row.style.display = text.includes(searchTerm) ? '' : 'none';
            });
        });


    </script>

