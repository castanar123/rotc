// Access control: Allow Admins, Instructors, Officers, and specific roles
check_login();
if (!in_array($_SESSION['role'], ['admin', 'instructor', 'officer', '1cl', '2cl', 'commandant', 'cadet', 'basic_cadet'])) {
    SecurityLogger::logSecurityEvent('UNAUTHORIZED_ACCESS', 'User attempted to access attendance logs without proper role', $_SESSION['user_id'] ?? null, 'HIGH');
    redirect_to_dashboard();
}

// Log access to attendance logs
SecurityLogger::logSecurityEvent('DATA_ACCESS', 'User accessed attendance logs', $_SESSION['user_id'], 'LOW');

// If cadet, only show their own logs
$cadet_filter = '';
if (in_array($_SESSION['role'], ['cadet', 'basic_cadet'])) {
    $cadet_filter = $_SESSION['user_id'];
}

// --- Filtering Logic ---
$filter_event = $_GET['event_name'] ?? '';
$filter_date = $_GET['event_date'] ?? '';
$filter_cadet = $_GET['cadet_name'] ?? '';

// --- Fetch Distinct Event Names for Filter Dropdown ---
$event_names = [];
$event_result = $link->query("SELECT DISTINCT event_name FROM attendance_logs ORDER BY event_name");
while ($row = $event_result->fetch_assoc()) {
    $event_names[] = $row['event_name'];
}

// --- Build SQL Query ---
$sql = "SELECT al.event_name, al.event_date, al.time_in, al.status, CONCAT(cp.first_name, ' ', cp.last_name) AS cadet_name, u.username AS logged_by_username
        FROM attendance_logs al
        JOIN cadet_profiles cp ON al.cadet_profile_id = cp.id
        JOIN users u ON al.logged_by_user_id = u.id";

$where_clauses = [];
$params = [];
$types = '';

if (!empty($filter_event)) {
    $where_clauses[] = "al.event_name = ?";
    $params[] = $filter_event;
    $types .= 's';
}
if (!empty($filter_date)) {
    $where_clauses[] = "al.event_date = ?";
    $params[] = $filter_date;
    $types .= 's';
}
if (!empty($filter_cadet)) {
    $where_clauses[] = "CONCAT(cp.first_name, ' ', cp.last_name) LIKE ?";
    $params[] = "%{$filter_cadet}%";
    $types .= 's';
}

if (!empty($where_clauses)) {
    $sql .= " WHERE " . implode(' AND ', $where_clauses);
}

// Order by date ascending to number training days chronologically
$sql .= " ORDER BY al.event_date ASC, al.time_in ASC";

$stmt = $link->prepare($sql);
if (!empty($params)) {
    $stmt->bind_param($types, ...$params);
}
$stmt->execute();
$result = $stmt->get_result();

// Group logs by date
$logs_by_date = [];
while ($row = $result->fetch_assoc()) {
    $logs_by_date[$row['event_date']][] = $row;
}

// If cadet, filter to only their records
if (in_array($_SESSION['role'], ['cadet', 'basic_cadet'])) {
    $sql .= " JOIN cadet_profiles cp2 ON al.cadet_profile_id = cp2.id WHERE cp2.user_id = ?";
    if (!empty($where_clauses)) {
        $sql .= " AND " . implode(' AND ', $where_clauses);
    }
    array_unshift($params, $_SESSION['user_id']);
    $types = 'i' . $types;
} else {
    if (!empty($where_clauses)) {
        $sql .= " WHERE " . implode(' AND ', $where_clauses);
    }
}

$stmt->close();
$link->close();
